"""Regenerates demo/js/themes-data.js from a folder of Ghostty theme files.

Usage: python3 -I demo/tools/gen-themes.py /Applications/Tarn.app/Contents/Resources/ghostty/themes

Each theme becomes one line: "Name":[bg, fg, cursor, selection-bg, selection-fg, 16 palette colors],
all as six hex digits without '#'. A missing cursor or selection color is an empty string.
The files come from the iTerm2-Color-Schemes set (MIT) that ships with Ghostty.
"""

import json
import pathlib
import re
import sys

HEX = re.compile(r"^#?([0-9a-fA-F]{6})$")


def color(text):
    m = HEX.match(text.strip())
    return m.group(1).lower() if m else ""


def parse(path):
    pal, keys = {}, {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" not in line or line.lstrip().startswith("#"):
            continue
        k, v = (s.strip() for s in line.split("=", 1))
        if k == "palette":
            i, _, c = v.partition("=")
            pal[int(i)] = color(c)
        else:
            keys[k] = color(v)
    if not keys.get("background") or not keys.get("foreground") or any(not pal.get(i) for i in range(16)):
        return None
    return [
        keys["background"], keys["foreground"], keys.get("cursor-color", ""),
        keys.get("selection-background", ""), keys.get("selection-foreground", ""),
        "".join(pal[i] for i in range(16)),
    ]


def main(src, dst):
    rows, skipped = [], []
    for path in sorted(src.iterdir(), key=lambda p: p.name.lower()):
        entry = parse(path)
        if entry is None:
            skipped.append(path.name)
            continue
        rows.append(f"  {json.dumps(path.name)}: {json.dumps(entry)},")
    head = (
        "// Generated by demo/tools/gen-themes.py from the Ghostty theme files; do not edit.\n"
        "// Palettes come from the iTerm2-Color-Schemes set (MIT, https://github.com/mbadolato/iTerm2-Color-Schemes).\n"
        "// Name: [background, foreground, cursor, selection-bg, selection-fg, 16 palette colors as one string]\n"
        "export const THEME_DATA = {\n"
    )
    dst.write_text(head + "\n".join(rows) + "\n};\n", encoding="utf-8")
    print(f"{len(rows)} themes, skipped: {skipped}")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]), pathlib.Path(__file__).resolve().parent.parent / "js" / "themes-data.js")
